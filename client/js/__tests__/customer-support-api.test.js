const { check, eq } = require('./helpers/assert');
const { wait } = require('./helpers/sandbox');
const { setup, response, defer, text } = require('./helpers/support-harness');
console.log('customer-support.js — Task 5 API integration');
const message = (id, value, kind = 'customer') => ({ id, text: value, kind, createdAt: '2026-10-21T08:00:00Z', senderName: kind === 'admin' ? 'BREEZE' : 'Guest' });
const compose = (r, value) => { r.get('breeze-support-message').value = value; r.get('breeze-support-message').fire('input'); };
const open = async r => { r.byClass('breeze-support-launcher').click(); await wait(); };
const submit = r => r.byClass('breeze-support-form').fire('submit');
(async () => {
    const r = setup('widget'); r.login(null);
    eq('initially closed widget does not contact chat APIs', r.calls.length, 0);
    await open(r);
    eq('opening checks existing conversation', r.calls.map(c => c.url), ['/api/support/conversation']);
    check('empty input cannot send', r.byClass('breeze-support-send').disabled);
    compose(r, 'Draft'); submit(r); await wait();
    eq('guest cannot send before entering contact information', r.calls.length, 1);
    r.get('breeze-support-name').value = 'Guest'; r.get('breeze-support-email').value = 'guest@example.test';
    const pending = defer(); r.state.handle = c => c.url === '/api/support/guest-session' ? pending.promise : undefined;
    submit(r); submit(r); await wait();
    const sends = r.calls.filter(c => c.options.method === 'POST');
    eq('double submit makes exactly one request', sends.length, 1);
    eq('first guest send uses atomic guest-session endpoint', sends[0].url, '/api/support/guest-session');
    check('first send includes required profile and UUID', sends[0].body.name === 'Guest' && sends[0].body.email === 'guest@example.test' && !!sends[0].body.clientMessageId);
    check('sending disables composer while keeping draft', r.byClass('breeze-support-send').disabled && r.get('breeze-support-message').disabled && r.get('breeze-support-message').value === 'Draft');
    eq('no fabricated message before API confirmation', r.byClass('breeze-support-transcript').children.length, 0);
    pending.resolve(response({ conversationId: '10', message: message('1', 'Draft'), replayed: false }, 201)); await wait();
    eq('confirmed message renders', text(r.byClass('breeze-support-transcript')).includes('Draft'), true);
    eq('confirmed send clears draft', r.get('breeze-support-message').value, '');
    check('existing guest session hides profile fields', r.byClass('breeze-support-guest').hidden);
    compose(r, '<script>literal</script>');
    r.state.handle = c => c.url === '/api/support/messages' ? Promise.reject(Error('offline')) : undefined;
    submit(r); await wait();
    eq('failed send preserves exact input', r.get('breeze-support-message').value, '<script>literal</script>');
    eq('failed send adds no transcript bubble', r.byClass('breeze-support-transcript').children.length, 1);
    const retryKey = r.calls.filter(c => c.options.method === 'POST').slice(-1)[0].body.clientMessageId;
    check('failed request has visible status and enabled manual retry', !r.get('breeze-support-unavailable').hidden && !r.byClass('breeze-support-send').disabled);
    r.state.handle = c => c.url === '/api/support/messages' ? response({ conversationId: '10', message: message('2', c.body.text), replayed: true }) : undefined;
    submit(r); await wait();
    eq('manual retry retains UUID', r.calls.filter(c => c.options.method === 'POST').slice(-1)[0].body.clientMessageId, retryKey);
    eq('confirmed text is rendered as textContent', r.byClass('breeze-support-transcript').children[1].children[0].children[0].textContent, '<script>literal</script>');
    eq('message HTML is never injected', r.byClass('breeze-support-transcript').children[1].children[0].children[0].innerHTML, '');
    r.state.handle = c => {
        if (c.url === '/api/support/conversation') return response({ conversation: { id: '10' } });
        if (c.url.endsWith('?before=2')) return response({ conversation: { id: '10' }, messages: [message('1', 'Older'), message('2', '<script>literal</script>')], nextBefore: null });
        if (c.url === '/api/support/conversation/messages') return response({ conversation: { id: '10' }, messages: [message('2', '<script>literal</script>'), message('3', 'Real reply', 'admin')], nextBefore: '2' });
    };
    r.byClass('breeze-support-refresh').click(); await wait();
    check('manual refresh loads Admin response', text(r.byClass('breeze-support-transcript')).includes('Real reply'));
    r.byClass('breeze-support-older').click(); await wait();
    eq('older pages prepend without duplicate bubbles', r.byClass('breeze-support-transcript').children.length, 3);
    check('end of history hides older button', r.byClass('breeze-support-older').hidden);
    compose(r, 'Expired draft'); r.state.handle = () => response({ code: 'SUPPORT_SESSION_EXPIRED' }, 401);
    submit(r); await wait();
    check('expired guest session clears old transcript and asks contact again', r.byClass('breeze-support-transcript').children.length === 0 && !r.byClass('breeze-support-guest').hidden);
    eq('expiry preserves unsent message', r.get('breeze-support-message').value, 'Expired draft');
    eq('no names, tokens or chat saved in browser storage', r.writes, []);

    const account = setup('widget'); account.login({ uid: 'customer-a' }, 'customer'); await wait(); await open(account);
    compose(account, 'Account message');
    account.state.handle = c => c.url === '/api/support/messages' ? response({ conversationId: '20', message: message('5', c.body.text) }, 201) : undefined;
    submit(account); await wait();
    const accountPost = account.calls.find(c => c.options.method === 'POST');
    eq('signed-in customer sends through own messages API', accountPost.url, '/api/support/messages');
    check('account POST includes Bearer and excludes guest profile', accountPost.options.headers.Authorization === 'Bearer customer-a' && accountPost.body.name === undefined);
    const revoked = setup('widget'); revoked.login({ uid: 'revoked' }, 'customer'); await wait(); await open(revoked);
    revoked.state.handle = c => c.url === '/api/support/messages' ? response({ conversationId: '30', message: message('8', c.body.text) }, 201) : undefined;
    compose(revoked, 'Private history'); submit(revoked); await wait();
    compose(revoked, 'Unsent after revocation'); revoked.state.handle = () => response({ code: 'SUPPORT_AUTH_REQUIRED' }, 401);
    revoked.byClass('breeze-support-refresh').click(); await wait();
    check('account access loss clears cached private messages and disables sending', revoked.byClass('breeze-support-transcript').children.length === 0 && revoked.byClass('breeze-support-send').disabled);
    eq('account access loss retains unsent text for login recovery', revoked.get('breeze-support-message').value, 'Unsent after revocation');
    compose(account, 'Line one'); const count = account.calls.length;
    account.get('breeze-support-message').fire('keydown', { key: 'Enter', shiftKey: true }); await wait();
    eq('Shift+Enter does not send', account.calls.length, count);
    account.get('breeze-support-message').fire('keydown', { key: 'Enter', isComposing: true }); await wait();
    eq('IME confirmation does not send', account.calls.length, count);
    const late = defer(); account.state.handle = c => c.url === '/api/support/messages' ? late.promise : undefined;
    submit(account); await wait(); account.login({ uid: 'customer-b' }, 'customer'); await wait();
    late.resolve(response({ conversationId: '20', message: message('6', 'Old account') }, 201)); await wait();
    check('late previous-account send cannot repopulate transcript or draft', account.byClass('breeze-support-transcript').children.length === 0 && account.get('breeze-support-message').value === '');
    account.state.roleResult = response({ firebase_uid: 'admin-a', role: 'admin' }); account.login({ uid: 'admin-a' }, 'admin'); await wait();
    check('Admin remains excluded from customer widget after integration', account.get('breeze-support').hidden);
    const denied = setup('widget'); denied.login({ uid: 'customer' }, 'customer'); await wait();
    denied.state.handle = () => response({ code: 'SUPPORT_CUSTOMER_ONLY' }, 403); await open(denied);
    check('server role denial hides widget and old data', denied.get('breeze-support').hidden);
})();
